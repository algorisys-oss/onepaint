//! The RGB display profiles exports are tagged with (happypaint
//! `engine/color/icc.ts`): ICC v4.2 matrix/TRC profiles generated in code,
//! deterministic (fixed creation date), with the sRGB transfer curve.

/// The profiles happypaint can tag.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RgbSpace {
    Srgb,
    DisplayP3,
}

impl RgbSpace {
    /// The profile description, also the PNG `iCCP` keyword.
    pub fn name(self) -> &'static str {
        match self {
            RgbSpace::Srgb => "sRGB IEC61966-2.1",
            RgbSpace::DisplayP3 => "Display P3",
        }
    }

    /// Red, green, blue colorants (Bradford-adapted to D50), `icc.ts:31-44`.
    fn primaries(self) -> [[f64; 3]; 3] {
        match self {
            RgbSpace::Srgb => [[0.436066, 0.222488, 0.013916], [0.385147, 0.716873, 0.097076], [0.143066, 0.060608, 0.714096]],
            RgbSpace::DisplayP3 => [[0.51512, 0.241182, -0.00105], [0.291965, 0.692236, 0.041885], [0.157153, 0.066576, 0.784378]],
        }
    }
}

const D50: [f64; 3] = [0.9642, 1.0, 0.8249];

fn s15f16(v: f64) -> [u8; 4] {
    ((v * 65536.0).round() as i32).to_be_bytes()
}

fn mluc(text: &str) -> Vec<u8> {
    let utf16: Vec<u8> = text.encode_utf16().flat_map(u16::to_be_bytes).collect();
    let mut t = b"mluc\0\0\0\0".to_vec();
    t.extend(1u32.to_be_bytes()); // one record
    t.extend(12u32.to_be_bytes()); // record size
    t.extend(b"enUS");
    t.extend((utf16.len() as u32).to_be_bytes());
    t.extend(28u32.to_be_bytes()); // string offset
    t.extend(utf16);
    t
}

fn xyz(v: [f64; 3]) -> Vec<u8> {
    let mut t = b"XYZ \0\0\0\0".to_vec();
    for c in v {
        t.extend(s15f16(c));
    }
    t
}

/// The sRGB curve as a `para` type 3 (`g, a, b, c, d`).
fn srgb_trc() -> Vec<u8> {
    let mut t = b"para\0\0\0\0".to_vec();
    t.extend(3u16.to_be_bytes());
    t.extend(0u16.to_be_bytes());
    for p in [2.4, 1.0 / 1.055, 0.055 / 1.055, 1.0 / 12.92, 0.04045] {
        t.extend(s15f16(p));
    }
    t
}

/// A complete profile for `space` (`buildIccProfile`).
pub fn build_icc_profile(space: RgbSpace) -> Vec<u8> {
    let [r, g, b] = space.primaries();
    let trc = srgb_trc();
    // Tags in table order; the three TRCs share one data block.
    let data: Vec<(&[u8; 4], Vec<u8>)> = vec![
        (b"desc", mluc(space.name())),
        (b"cprt", mluc("CC0 — generated by happypaint")),
        (b"wtpt", xyz(D50)),
        (b"rXYZ", xyz(r)),
        (b"gXYZ", xyz(g)),
        (b"bXYZ", xyz(b)),
        (b"rTRC", trc.clone()),
        (b"gTRC", trc.clone()),
        (b"bTRC", trc),
    ];
    let table_len = 4 + 12 * data.len();
    let mut body: Vec<u8> = Vec::new();
    let mut entries: Vec<(&[u8; 4], u32, u32)> = Vec::new();
    let mut shared_trc: Option<(u32, u32)> = None;
    for (sig, bytes) in &data {
        let is_trc = sig.ends_with(b"TRC");
        if let (true, Some((o, l))) = (is_trc, shared_trc) {
            entries.push((sig, o, l));
            continue;
        }
        let off = (128 + table_len + body.len()) as u32;
        body.extend(bytes);
        while !body.len().is_multiple_of(4) {
            body.push(0);
        }
        entries.push((sig, off, bytes.len() as u32));
        if is_trc {
            shared_trc = Some((off, bytes.len() as u32));
        }
    }
    let size = 128 + table_len + body.len();
    let mut p = Vec::with_capacity(size);
    p.extend((size as u32).to_be_bytes());
    p.extend([0u8; 4]); // preferred CMM
    p.extend(0x0420_0000u32.to_be_bytes());
    p.extend(b"mntrRGB XYZ ");
    for v in [2026u16, 1, 1, 0, 0, 0] {
        p.extend(v.to_be_bytes());
    }
    p.extend(b"acsp");
    p.extend([0u8; 4 + 4 + 4 + 4 + 8]); // platform, flags, manufacturer, model, attributes
    p.extend(0u32.to_be_bytes()); // perceptual
    for c in D50 {
        p.extend(s15f16(c));
    }
    p.extend([0u8; 4 + 16 + 28]); // creator, profile id, reserved
    p.extend((entries.len() as u32).to_be_bytes());
    for (sig, off, len) in entries {
        p.extend(sig);
        p.extend(off.to_be_bytes());
        p.extend(len.to_be_bytes());
    }
    p.extend(body);
    p
}

/// Convert straight RGBA8 tagged with an embedded RGB `profile` to sRGB in
/// place (relative colorimetric; alpha untouched). Browsers do this on decode,
/// so happypaint imports arrive in sRGB. Returns false, leaving the pixels as
/// they are, for a profile that is not an RGB display profile or won't parse.
pub fn rgba8_to_srgb(profile: &[u8], rgba: &mut [u8]) -> bool {
    use moxcms::{ColorProfile, DataColorSpace, Layout, TransformOptions};
    let Ok(src) = ColorProfile::new_from_slice(profile) else { return false };
    if src.color_space != DataColorSpace::Rgb {
        return false;
    }
    let Ok(t) = src.create_transform_8bit(Layout::Rgba, &ColorProfile::new_srgb(), Layout::Rgba, TransformOptions::default()) else {
        return false;
    };
    let mut out = vec![0u8; rgba.len()];
    if t.transform(rgba, &mut out).is_err() {
        return false;
    }
    rgba.copy_from_slice(&out);
    true
}

#[cfg(test)]
mod tests {
    use super::*;
    use moxcms::{ColorProfile, Layout, TransformOptions};

    #[test]
    fn the_srgb_profile_parses_and_is_srgb() {
        let bytes = build_icc_profile(RgbSpace::Srgb);
        assert_eq!(bytes.len() % 4, 0);
        assert_eq!(&bytes[36..40], b"acsp");
        assert_eq!(u32::from_be_bytes(bytes[0..4].try_into().unwrap()) as usize, bytes.len());
        assert_eq!(build_icc_profile(RgbSpace::Srgb), bytes, "deterministic");
        let ours = ColorProfile::new_from_slice(&bytes).unwrap();
        let t = ours.create_transform_f32(Layout::Rgb, &ColorProfile::new_srgb(), Layout::Rgb, TransformOptions::default()).unwrap();
        let src = [0.0f32, 0.0, 0.0, 1.0, 1.0, 1.0, 0.8, 0.3, 0.1, 0.2, 0.6, 0.9];
        let mut dst = [0.0f32; 12];
        t.transform(&src, &mut dst).unwrap();
        for (a, b) in src.iter().zip(dst) {
            assert!((a - b).abs() < 2e-3, "{src:?} → {dst:?}");
        }
        // P3 differs from sRGB.
        let p3 = ColorProfile::new_from_slice(&build_icc_profile(RgbSpace::DisplayP3)).unwrap();
        let t = p3.create_transform_f32(Layout::Rgb, &ColorProfile::new_srgb(), Layout::Rgb, TransformOptions::default()).unwrap();
        let mut red = [0.0f32; 3];
        t.transform(&[1.0, 0.0, 0.0], &mut red).unwrap();
        assert!(red[0] >= 0.99 && red[1] < 0.05, "P3 red is out of sRGB: {red:?}");
    }

    #[test]
    fn p3_pixels_convert_to_srgb_on_import() {
        let mut px = [255u8, 0, 0, 128, 120, 120, 120, 255];
        assert!(rgba8_to_srgb(&build_icc_profile(RgbSpace::DisplayP3), &mut px));
        assert_eq!(px[3], 128, "alpha kept");
        assert!(px[0] == 255 && px[1] == 0, "P3 red clips to sRGB red: {px:?}");
        assert!(px[4..7].iter().all(|&v| v.abs_diff(120) <= 1), "greys stay put: {px:?}");
        let mut srgb = [10u8, 200, 90, 255];
        assert!(rgba8_to_srgb(&build_icc_profile(RgbSpace::Srgb), &mut srgb));
        assert!(srgb.iter().zip([10u8, 200, 90, 255]).all(|(a, b)| a.abs_diff(b) <= 1));
        assert!(!rgba8_to_srgb(b"not a profile", &mut srgb));
    }
}
